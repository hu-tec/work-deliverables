"""Build offline full-text search data for the published catalog (stdlib only)."""

import argparse
import html
import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "search-index.js"
GUIDES = "04_작업_가이드/AI_작업요청_프롬프트_가이드"


class PageText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self.blocked = []

    def handle_starttag(self, tag, attrs):
        if tag in {"head", "script", "style", "template"}:
            self.blocked.append(tag)
        if not self.blocked:
            self.parts.append(" ")
            self.parts.extend(value for key, value in attrs
                              if key in {"alt", "aria-label", "placeholder"} and value)

    def handle_endtag(self, tag):
        if self.blocked and tag == self.blocked[-1]:
            self.blocked.pop()
        if not self.blocked:
            self.parts.append(" ")

    def handle_data(self, data):
        if not self.blocked:
            self.parts.append(data)


def build():
    catalog = (ROOT / "index.html").read_text(encoding="utf-8")
    paths = set(re.findall(r'"path":\s*"([^"\n]+\.(?:html|md))"', catalog))
    paths.update(file.relative_to(ROOT).as_posix() for file in (ROOT / GUIDES).glob("*.md"))
    entries = []
    for relative in sorted(paths):
        file = (ROOT / relative).resolve()
        if not file.is_relative_to(ROOT) or not file.is_file():
            raise ValueError(f"Missing or invalid catalog source: {relative}")
        source = file.read_text(encoding="utf-8-sig")
        kind = "guide" if relative.startswith(GUIDES + "/") else file.suffix[1:]
        if file.suffix == ".html":
            parser = PageText()
            parser.feed(source)
            content = re.sub(r"\s+", " ", " ".join(parser.parts)).strip()
            heading = re.search(r"<title[^>]*>(.*?)</title>", source, re.I | re.S)
            title = html.unescape(re.sub(r"<[^>]+>", "", heading[1])).strip() if heading else file.stem
        else:
            content = source.replace("\r\n", "\n")
            heading = re.search(r"^#\s+(.+)", content, re.M)
            title = heading[1].strip() if heading else file.stem
        entries.append({"path": relative, "kind": kind, "title": title, "content": content})
    payload = json.dumps(entries, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return "// Generated by python scripts/build-search-index.py.\nwindow.DELIVERABLE_SEARCH_INDEX = " + payload + ";\n", len(entries)


if __name__ == "__main__":
    args = argparse.ArgumentParser()
    args.add_argument("--check", action="store_true")
    options = args.parse_args()
    generated, count = build()
    if options.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Search index is stale. Run python scripts/build-search-index.py")
        print(f"Search index is current: {count} documents")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(f"Indexed {count} documents ({len(generated.encode('utf-8')):,} bytes)")
