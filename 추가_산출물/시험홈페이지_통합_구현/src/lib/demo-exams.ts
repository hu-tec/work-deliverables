/** 기준일 대비 접수 상태 계산 (date 문자열 비교, YYYY-MM-DD) */
export function computeRegisterStatus(
  ex: ExamOffering,
  today: string = TODAY,
): RegisterStatus {
  if (today < ex.registerStart) return "접수 전";
  if (today > ex.registerEnd) return "접수 완료"; // 접수 마감
  return "접수 중";
}

export function getExamById(id: string): ExamOffering | undefined {
  return DEMO_EXAMS.find((e) => e.id === id);
}
